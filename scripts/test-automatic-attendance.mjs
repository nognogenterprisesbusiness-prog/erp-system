import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { withLocalFixture } from "./local-integration-fixture.mjs";
const project = "20000000-0000-0000-0000-000000000001";
const site = "40000000-0000-0000-0000-000000000001";
await withLocalFixture(async ({ sql, as, users, result }) => {
  const employee = randomUUID();
  const assignment = randomUUID();
  await sql(`insert into public.employees(id,code,first_name,last_name,category_id,employment_type,hire_date,created_by,updated_by)
    select '${employee}','TEST-${employee.slice(0,8).toUpperCase()}','Integration','Employee',category_id,employment_type,'2026-01-01','${users.admin}','${users.admin}' from public.employees where code='EMP-001';
    insert into public.employee_project_assignments(id,employee_id,project_id,project_site_id,position_title,start_date,assigned_by)
    values('${assignment}','${employee}','${project}','${site}','Integration worker','2026-01-01','${users.admin}');`);
  await as("admin", `select public.post_labor_rate('${employee}','daily',750,'2026-01-01',null)`);
  await assert.rejects(as("foreman", `select * from public.get_project_attendance_operations('20000000-0000-0000-0000-000000000003',0,20)`));
  await assert.rejects(as("foreman", `select public.post_labor_rate('${employee}','hourly',100,'2026-09-01',null)`));
  await as("admin", `select public.post_labor_rate('${employee}','hourly',100,'2026-09-01',null)`);
  await assert.rejects(as("foreman", `select public.get_attendance_rate_basis('${employee}','2026-09-24')`));
  await as("admin", `select public.set_employee_attendance_basis('${employee}','daily')`);
  await assert.rejects(as("foreman", `select public.set_employee_attendance_basis('${employee}','hourly')`));
  const key = randomUUID();
  const post = `select public.post_project_attendance('${key}','${assignment}','2026-09-24','present',8,'daily',0.5,'Integration half day')`;
  const attendance = result(await as("foreman", post));
  assert.ok(attendance);
  assert.equal(result(await as("foreman", post)), attendance);
  await assert.rejects(as("foreman", post.replace(key, randomUUID())));
  await assert.rejects(as("engineer", post.replace(key, randomUUID())));
  await assert.rejects(as("warehouse_staff", post.replace(key, randomUUID())));
  const cost = Number(await sql(`select cost_total from public.project_attendance where id='${attendance}'`));
  assert.equal(cost, 375);
  const full = result(await as("foreman", `select public.post_project_attendance('${randomUUID()}','${assignment}','2026-09-23','present',8,'daily',1,'Integration full day')`));
  assert.equal(Number(await sql(`select cost_total from public.project_attendance where id='${full}'`)), 750);
  await as("admin", `select public.set_employee_attendance_basis('${employee}','hourly')`);
  const hourly = result(await as("foreman", `select public.post_project_attendance('${randomUUID()}','${assignment}','2026-09-22','present',7.5,'hourly',null,'Integration hourly day')`));
  assert.equal(Number(await sql(`select cost_total from public.project_attendance where id='${hourly}'`)), 750);
  await assert.rejects(as("foreman", `select public.post_project_attendance('${randomUUID()}','${assignment}','2026-09-21','present',25,'hourly',null,'Integration excess hours')`));
  const concurrent = await Promise.allSettled([1,2].map(() => as("foreman", `select public.post_project_attendance('${randomUUID()}','${assignment}','2026-09-20','present',8,'hourly',null,'Integration concurrent day')`)));
  assert.equal(concurrent.filter((r) => r.status === "fulfilled").length, 1);
  assert.equal(concurrent.filter((r) => r.status === "rejected").length, 1);
  const operations = await as("foreman", `select to_jsonb(x) from public.get_project_attendance_operations('${project}',0,20) x`);
  assert.equal(operations.includes('"rate_snapshot"'), false);
  assert.equal(operations.includes('"cost_total"'), false);
  const report = result(await as("foreman", `select public.save_daily_report('${randomUUID()}','${project}','${site}','2026-09-24','Clear','Integration work','Half day completed','','','',false)`));
  const before = await sql(`select sum(cost_total) from public.project_attendance where project_id='${project}'`);
  const attach = `select public.attach_daily_report_resource('${report}','attendance','${attendance}')`;
  await as("foreman", attach);
  await as("foreman", attach);
  assert.equal(Number(await sql(`select count(*) from public.daily_report_resource_links where report_id='${report}'`)), 1);
  assert.equal(await sql(`select sum(cost_total) from public.project_attendance where project_id='${project}'`), before);
  await assert.rejects(as("foreman", `select public.reverse_project_attendance('${randomUUID()}','${attendance}','Integration correction')`));
  await as("admin", `select public.reverse_project_attendance('${randomUUID()}','${attendance}','Integration correction')`);
  assert.ok((await as("foreman", `select reversed from public.list_daily_report_resources('${report}',true,0,20)`)).split("\n").includes("t"));
  console.log("PASS: daily/hourly costing, ambiguity, retry/concurrent duplicate denial, role/wage/cross-project denial, financial redaction, report links, no double posting and Admin reversal.");
});
