import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { withIsolatedPostgres } from './isolated-postgres-fixture.mjs';

const project='20000000-0000-0000-0000-000000000001',site='40000000-0000-0000-0000-000000000001';
const warehouse='30000000-0000-0000-0000-000000000001',other='30000000-0000-0000-0000-000000000002';
const material='60000000-0000-0000-0000-000000000001';
await withIsolatedPostgres(async({sql,as,result,scalar})=>{
  const value=async(q)=>scalar(await sql(q));
  const request=result(await as('foreman',`select public.submit_mobile_material_request('${randomUUID()}','${project}','${site}','Warehouse selection','[{"materialId":"${material}","quantity":"3"}]')`));
  await sql(`delete from public.project_warehouses where project_id='${project}'`);
  const balances=await value('select jsonb_agg(to_jsonb(b) order by id) from public.inventory_balances b');
  assert.equal(scalar(await as('admin',`select count(*) from public.get_request_warehouse_choices('${request}','request')`)),'2');
  const key=randomUUID(),assign=`select public.assign_request_warehouse('${key}','${request}','request','${warehouse}')`;
  for(const role of ['foreman','engineer','finance','warehouse_staff']) {
    await assert.rejects(as(role,assign),/not authorized|unavailable/);
  }
  await assert.rejects(sql(`set role anon; ${assign}`),/permission denied/);
  await assert.rejects(as('admin',assign.replace(`'${key}'`,'null')),/Choose a source warehouse/);
  assert.equal(await value(`select count(*) from public.project_warehouses where project_id='${project}'`),'0');
  const saved=await Promise.all([as('admin',assign),as('admin',assign)]);
  for(const output of saved) assert.equal(result(output),request);
  assert.equal(await value(`select count(*) from public.project_warehouses where project_id='${project}'`),'0');
  assert.equal(await value(`select count(*) from private.request_warehouse_assignments where target_id='${request}'`),'1');
  assert.equal(await value(`select source_warehouse_id from public.material_requests where id='${request}'`),warehouse);
  assert.equal(await value('select jsonb_agg(to_jsonb(b) order by id) from public.inventory_balances b'),balances);
  assert.equal(await value(`select count(*) from public.material_request_reservations r join public.material_request_lines l on l.id=r.request_line_id where l.request_id='${request}'`),'0');
  assert.equal(scalar(await as('warehouse_staff',`select count(*) from public.get_request_warehouse_choices('${request}','request')`)),'2');
  await assert.rejects(as('admin',assign.replace(warehouse,other)),/different/);
  assert.equal(await value(`select count(*) from public.project_warehouses where project_id='${project}' and warehouse_id='${other}'`),'0');
  const line=await value(`select id from public.material_request_lines where request_id='${request}'`);
  const track = async (role='foreman') => JSON.parse(scalar(await as(role,`select row_to_json(t) from public.get_material_request_tracking(array['${request}']::uuid[]) t`)));
  const initialStock=(await track()).site_on_hand;
  assert.equal(scalar(await as('finance',`select count(*) from public.get_material_request_tracking(array['${request}']::uuid[])`)),'0');
  for (const role of ['engineer','foreman','admin']) assert.equal((await track(role)).site_on_hand,initialStock);
  await assert.rejects(sql(`set role anon; select * from public.get_material_request_tracking(array['${request}']::uuid[])`),/permission denied/);
  assert.equal(scalar(await as('foreman',`select count(*) from public.get_material_request_tracking(array['${randomUUID()}']::uuid[])`)),'0');
  await as('engineer',`select public.decide_material_request('${randomUUID()}','${request}','{"${line}":"3"}',null)`);
  assert.equal(result(await as('admin',assign)),request);
  assert.equal(Number((await track()).reserved),3);
  assert.equal((await track()).site_on_hand,initialStock);
  assert.equal((await track('warehouse_staff')).site_on_hand,null);
  const dispatch=`select public.dispatch_approved_request_line_with_manifest('${randomUUID()}','${line}',3,current_date,'Request-only source',null,'Test truck','Test driver','REQUEST-SOURCE')`;
  const transfers=await Promise.all([as('warehouse_staff',dispatch),as('warehouse_staff',dispatch)]);
  assert.equal(result(transfers[0]),result(transfers[1]));
  assert.equal(Number((await track()).dispatched),3);
  assert.equal((await track()).site_on_hand,initialStock);
  const item=await value(`select transfer_item_id from public.material_request_dispatches where request_line_id='${line}'`);
  await as('foreman',`select public.receive_request_transfer_with_inspection('${randomUUID()}','${item}',2,current_date,'Counted receipt','accepted',null)`);
  assert.equal(await value(`select dispatched_quantity-received_quantity from public.inventory_transfer_items where id='${item}'`),'1.0000');
  assert.equal(await value(`select count(*) from public.project_warehouses where project_id='${project}'`),'0');
  assert.equal(Number((await track()).received),2);
  assert.equal(Number((await track()).site_on_hand),Number(initialStock)+2);
  assert.equal(Number((await track()).site_available),Number(initialStock)+2);
  const location=await value(`select id from public.inventory_locations where project_site_id='${site}'`);
  const unit=await value(`select base_unit_id from public.materials where id='${material}'`);
  await as('foreman',`select public.consume_site_material('${randomUUID()}','${material}','${location}','${project}',1,'${unit}','TRACK-USE',current_date,'Actual site use')`);
  assert.equal(Number((await track()).site_on_hand),Number(initialStock)+1);
  assert.equal(Number((await track()).received),2);
  assert.ok(!('unit_cost' in await track()));
  await sql(`update public.project_sites set foreman_id=null where id='${site}'; delete from public.project_assignments where project_id='${project}' and user_id='10000000-0000-0000-0000-000000000004'`);
  assert.equal(scalar(await as('foreman',`select count(*) from public.get_material_request_tracking(array['${request}']::uuid[])`)),'0');
  console.log('PASS: scoped quantity-only tracking shows reservation/transit separately from current site stock and partial receipt.');
  console.log('PASS: Request-only source selection without project links, denied roles, concurrent/replayed saves and dispatch, unchanged stock before approval and partial site receipt.');
});
